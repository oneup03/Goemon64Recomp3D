#!/usr/bin/env python3
"""Writes patches/overlay_files.h: each code file's section in the decompressed
ROM layout the recompiler ran on, by file id, from the symbol file.

The game reads the retail ROM and decompresses its files itself, as on the
N64. The recompiled overlays are registered at their decompressed addresses,
so patches/required.c registers a loaded file by its id instead of by the
(compressed) ROM address the game read it from. Rerun this when
Goemon64RecompSyms changes:

    python3 tools/gen_overlay_files.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
syms = (root / "Goemon64RecompSyms" / "mnsg.syms.toml").read_text()
sections = re.findall(
    r'\[\[section\]\]\s*name\s*=\s*"\.file_(\d+)"\s*rom\s*=\s*(0x[0-9A-Fa-f]+)\s*vram\s*=\s*0x[0-9A-Fa-f]+\s*size\s*=\s*(0x[0-9A-Fa-f]+)',
    syms)
rows = sorted((int(n), int(rom, 16), int(size, 16)) for n, rom, size in sections)

out = [
    "// Generated by tools/gen_overlay_files.py from Goemon64RecompSyms/mnsg.syms.toml.",
    "// The code files and their sections in the decompressed ROM layout the",
    "// recompiler ran on (each section starts at its file's decompressed address).",
    "#ifndef __OVERLAY_FILES_H__",
    "#define __OVERLAY_FILES_H__",
    "",
    '#include "PR/ultratypes.h"',
    "",
    "typedef struct OverlayFile {",
    "    u16 file_id;",
    "    u32 rom;",
    "    u32 size;",
    "} OverlayFile;",
    "",
    "static const OverlayFile overlay_files[] = {",
]
out += ["    { %d, 0x%08X, 0x%06X }," % row for row in rows]
out += ["};", "", "#endif", ""]
(root / "patches" / "overlay_files.h").write_text("\n".join(out))
print("patches/overlay_files.h: %d code files" % len(rows))
